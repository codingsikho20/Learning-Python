# Arithmetic Operators → +, -, *, /, %, //, **

a = 10
b = 3

print("Arithmetic Operators:")
print(a + b)   # 13
print(a - b)   # 7
print(a * b)   # 30
print(a / b)   # 3.333...
print(a % b)   # 1
print(a // b)  # 3
print(a ** b)  # 1000
print("Arithmetic Operators:")

